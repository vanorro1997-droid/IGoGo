-- ============================================================================
-- IGoGo — схема базы данных (PostgreSQL 15, см. docker-compose.yml)
--
-- Источники полей:
--   main.go            -> /api/2gis/search (q, location, region_id, city_id,
--                         type, fields, sort, page, page_size, radius, locale),
--                         /api/weather (location -> current.json),
--                         заголовки X-API-Key / Authorization для будущей авторизации.
--   frontend/index.html-> item.id/name/address_name/type/point.lat/point.lon;
--                         weather: location.name/region/country/tz_id/localtime,
--                         current.temp_c/feelslike_c/condition.text+icon,
--                         wind_kph/wind_dir/humidity/precip_mm.
--
-- Решения по производительности:
--   * координаты хранятся отдельными double precision колонками (индексируются),
--     а «сырой» ответ внешнего API — в jsonb (для восстановления/отладки);
--   * справочники — маленькие smallint-таблицы, а не длинные строки в каждой записи;
--   * частичные индексы под «маршруты, которые строятся сейчас» (draft/building);
--   * UNIQUE (city_id, forecast_date, source) позволяет идемпотентно UPDATE ... ON CONFLICT
--     при обновлении прогноза погоды;
--   * external_api_cache снижает число платных вызовов 2ГИС/WeatherAPI;
--   * если понадобятся поиск в радиусе/пересечения — подключите PostGIS и
--     замените пары lat/lon на geography(Point, 4326) с GiST-индексом.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- Типы и справочники
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'user_status') THEN
        CREATE TYPE user_status AS ENUM ('active', 'blocked');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'search_status') THEN
        CREATE TYPE search_status AS ENUM ('pending', 'running', 'success', 'failed');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'route_status') THEN
        CREATE TYPE route_status AS ENUM ('draft', 'building', 'ready', 'failed', 'archived');
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS user_role (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL,
    name text NOT NULL,
    CONSTRAINT user_role_code_uq UNIQUE (code)
);

COMMENT ON TABLE user_role IS 'Роли пользователя: user, admin.';

-- Виды маршрутов (то, что выбирает пользователь: авто, пешком, вело, транспорт).
CREATE TABLE IF NOT EXISTS route_type (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL,
    name text NOT NULL,
    CONSTRAINT route_type_code_uq UNIQUE (code)
);

-- Транспорт внутри сегмента маршрута: пешком, авто, метро, автобус и т.п.
CREATE TABLE IF NOT EXISTS transport_mode (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL,
    name text NOT NULL,
    CONSTRAINT transport_mode_code_uq UNIQUE (code)
);

-- ---------------------------------------------------------------------------
-- Авторизованный пользователь
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS app_user (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email         text NOT NULL,
    password_hash text NOT NULL,               -- argon2id/bcrypt, NEVER plaintext
    display_name  text,
    role_id       smallint NOT NULL DEFAULT 1
                  REFERENCES user_role (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status        user_status NOT NULL DEFAULT 'active',
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    last_login_at timestamptz,
    CONSTRAINT app_user_email_normalized_ck CHECK (email = lower(email)),
    CONSTRAINT app_user_password_ck CHECK (length(password_hash) > 0)
);

-- email уже нормализован CHECK-ом, поэтому обычный unique быстрее функционального.
CREATE UNIQUE INDEX IF NOT EXISTS app_user_email_uq ON app_user (email);
CREATE INDEX IF NOT EXISTS app_user_status_idx ON app_user (status) WHERE status <> 'active';

COMMENT ON COLUMN app_user.password_hash IS 'Хэш пароля; приложение обязано приводить email к lower().';

-- Сессии/refresh-токены: сырой токен в БД не хранится, только его SHA-256.
CREATE TABLE IF NOT EXISTS user_session (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    token_hash char(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz,
    user_agent text,
    ip         inet,
    CONSTRAINT user_session_token_uq UNIQUE (token_hash),
    CONSTRAINT user_session_expiry_ck CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS user_session_user_idx ON user_session (user_id, expires_at DESC);
CREATE INDEX IF NOT EXISTS user_session_active_idx ON user_session (expires_at)
    WHERE revoked_at IS NULL;

-- ---------------------------------------------------------------------------
-- Города, используемые в поиске
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS city (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    external_id text,                          -- 2GIS city_id / region_id
    name        text NOT NULL,
    region      text,                          -- WeatherAPI location.region
    country     text,                          -- WeatherAPI location.country
    latitude    double precision NOT NULL,
    longitude   double precision NOT NULL,
    timezone    text,                          -- WeatherAPI location.tz_id
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT city_external_id_uq UNIQUE (external_id),
    CONSTRAINT city_lat_ck CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT city_lon_ck CHECK (longitude BETWEEN -180 AND 180)
);

CREATE UNIQUE INDEX IF NOT EXISTS city_identity_uq
    ON city (lower(name), lower(coalesce(region, '')), lower(coalesce(country, '')));
CREATE INDEX IF NOT EXISTS city_name_lower_idx ON city (lower(name));
CREATE INDEX IF NOT EXISTS city_coords_idx ON city (latitude, longitude);

-- Альтернативные/локализованные названия (locale ru_RU / en_US из Forms API).
CREATE TABLE IF NOT EXISTS city_alias (
    city_id    bigint NOT NULL REFERENCES city (id) ON DELETE CASCADE,
    alias      text NOT NULL,
    locale_code text NOT NULL DEFAULT 'ru_RU',
    PRIMARY KEY (city_id, alias, locale_code)
);

CREATE INDEX IF NOT EXISTS city_alias_lookup_idx ON city_alias (lower(alias), locale_code);

-- ---------------------------------------------------------------------------
-- Точки (результаты 2ГИС и адреса маршрутов)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS place (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    external_id text,                          -- 2GIS item.id
    city_id     bigint REFERENCES city (id) ON DELETE SET NULL,
    name        text NOT NULL,                 -- item.name
    address     text,                          -- item.address_name
    type        text,                          -- item.type
    latitude    double precision NOT NULL,      -- item.point.lat
    longitude   double precision NOT NULL,      -- item.point.lon
    raw         jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT place_external_id_uq UNIQUE (external_id),
    CONSTRAINT place_lat_ck CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT place_lon_ck CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX IF NOT EXISTS place_city_name_idx ON place (city_id, lower(name));
CREATE INDEX IF NOT EXISTS place_coords_idx ON place (latitude, longitude);

-- ---------------------------------------------------------------------------
-- Сохранённые поиски маршрутов
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS saved_search (
    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id             bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    name                text NOT NULL,                    -- «Дом -> Работа»
    query_text          text,                             -- 2GIS q (может отсутствовать у маршрута)
    route_type_id       smallint NOT NULL DEFAULT 1
                        REFERENCES route_type (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    origin_city_id      bigint REFERENCES city (id) ON DELETE SET NULL,
    destination_city_id bigint REFERENCES city (id) ON DELETE SET NULL,
    origin_lat          double precision NOT NULL,
    origin_lon          double precision NOT NULL,
    destination_lat     double precision NOT NULL,
    destination_lon     double precision NOT NULL,
    radius_m            integer NOT NULL DEFAULT 1000 CHECK (radius_m > 0),
    sort_code           text NOT NULL DEFAULT 'distance'
                        CHECK (sort_code IN ('distance', 'relevance')),
    locale_code         text NOT NULL DEFAULT 'ru_RU'
                        CHECK (locale_code IN ('ru_RU', 'en_US')),
    page_number         integer NOT NULL DEFAULT 1 CHECK (page_number > 0),
    page_size           integer NOT NULL DEFAULT 10 CHECK (page_size BETWEEN 1 AND 50),
    fields              text[] NOT NULL DEFAULT ARRAY['items.point', 'items.address']::text[],
    extra_params        jsonb NOT NULL DEFAULT '{}'::jsonb, -- type, region_id, city_id и др.
    is_favorite         boolean NOT NULL DEFAULT false,
    last_run_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT saved_search_name_uq UNIQUE (user_id, name),
    CONSTRAINT saved_search_origin_lat_ck CHECK (origin_lat BETWEEN -90 AND 90),
    CONSTRAINT saved_search_origin_lon_ck CHECK (origin_lon BETWEEN -180 AND 180),
    CONSTRAINT saved_search_dest_lat_ck CHECK (destination_lat BETWEEN -90 AND 90),
    CONSTRAINT saved_search_dest_lon_ck CHECK (destination_lon BETWEEN -180 AND 180)
);

CREATE INDEX IF NOT EXISTS saved_search_user_recent_idx ON saved_search (user_id, last_run_at DESC NULLS LAST);
CREATE INDEX IF NOT EXISTS saved_search_extra_params_idx ON saved_search USING GIN (extra_params jsonb_path_ops);

COMMENT ON COLUMN saved_search.fields IS 'Значение параметра 2GIS fields из main.go.';
COMMENT ON COLUMN saved_search.extra_params IS 'Доп. параметры 2GIS: type, region_id, city_id, sort и т.д.';

-- ---------------------------------------------------------------------------
-- История запусков поиска и результаты
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS search_run (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    saved_search_id bigint REFERENCES saved_search (id) ON DELETE SET NULL,
    status         search_status NOT NULL DEFAULT 'pending',
    started_at     timestamptz NOT NULL DEFAULT now(),
    finished_at    timestamptz,
    result_count   integer NOT NULL DEFAULT 0 CHECK (result_count >= 0),
    error_message  text,
    CONSTRAINT search_run_time_ck CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE INDEX IF NOT EXISTS search_run_user_started_idx ON search_run (user_id, started_at DESC);
CREATE INDEX IF NOT EXISTS search_run_saved_idx ON search_run (saved_search_id, started_at DESC);
CREATE INDEX IF NOT EXISTS search_run_active_idx ON search_run (started_at)
    WHERE status IN ('pending', 'running');

CREATE TABLE IF NOT EXISTS search_result (
    search_run_id bigint NOT NULL REFERENCES search_run (id) ON DELETE CASCADE,
    place_id      bigint NOT NULL REFERENCES place (id) ON DELETE RESTRICT,
    rank          smallint NOT NULL CHECK (rank > 0),
    distance_m    integer CHECK (distance_m >= 0),
    PRIMARY KEY (search_run_id, place_id)
);

CREATE INDEX IF NOT EXISTS search_result_rank_idx ON search_result (search_run_id, rank);

-- История всех запросов авторизованного пользователя к API приложения.
-- search_run/search_result хранят результаты поиска, а эта таблица — сам факт
-- обращения (включая ошибки и запросы без сохранённого поиска).
CREATE TABLE IF NOT EXISTS api_request_log (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    method       text NOT NULL,
    path         text NOT NULL,
    query_params jsonb NOT NULL DEFAULT '{}'::jsonb,
    provider     text CHECK (provider IN ('2gis', 'weatherapi')),
    status_code  smallint NOT NULL CHECK (status_code BETWEEN 100 AND 599),
    duration_ms  integer NOT NULL CHECK (duration_ms >= 0),
    ip           inet,
    user_agent   text,
    error_message text,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS api_request_log_user_created_idx
    ON api_request_log (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS api_request_log_provider_idx
    ON api_request_log (provider, created_at DESC) WHERE provider IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Маршруты, которые строятся сейчас
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS route (
    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id             bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    saved_search_id     bigint REFERENCES saved_search (id) ON DELETE SET NULL,
    search_run_id       bigint REFERENCES search_run (id) ON DELETE SET NULL,
    route_type_id       smallint NOT NULL DEFAULT 1
                        REFERENCES route_type (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status              route_status NOT NULL DEFAULT 'draft',
    origin_city_id      bigint REFERENCES city (id) ON DELETE SET NULL,
    destination_city_id bigint REFERENCES city (id) ON DELETE SET NULL,
    origin_lat          double precision NOT NULL,
    origin_lon          double precision NOT NULL,
    destination_lat     double precision NOT NULL,
    destination_lon     double precision NOT NULL,
    distance_m          integer CHECK (distance_m >= 0),
    duration_s          integer CHECK (duration_s >= 0),
    departure_at        timestamptz,
    arrival_at          timestamptz,
    transfers           smallint NOT NULL DEFAULT 0 CHECK (transfers >= 0),
    fare_amount         numeric(10, 2) CHECK (fare_amount >= 0),
    geometry            jsonb NOT NULL DEFAULT '{}'::jsonb, -- GeoJSON LineString
    raw                 jsonb NOT NULL DEFAULT '{}'::jsonb, -- ответ маршрутизатора
    expires_at          timestamptz,                        -- TTL для «сейчас»
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT route_origin_lat_ck CHECK (origin_lat BETWEEN -90 AND 90),
    CONSTRAINT route_origin_lon_ck CHECK (origin_lon BETWEEN -180 AND 180),
    CONSTRAINT route_dest_lat_ck CHECK (destination_lat BETWEEN -90 AND 90),
    CONSTRAINT route_dest_lon_ck CHECK (destination_lon BETWEEN -180 AND 180),
    CONSTRAINT route_time_ck CHECK (
        arrival_at IS NULL OR departure_at IS NULL OR arrival_at >= departure_at
    )
);

-- Основной путь выборки приложения: мои маршруты + статус + свежесть.
CREATE INDEX IF NOT EXISTS route_user_status_idx ON route (user_id, status, updated_at DESC);
-- «Строятся сейчас» — компактный частичный индекс, не трогает архив.
CREATE INDEX IF NOT EXISTS route_building_idx ON route (updated_at DESC)
    WHERE status IN ('draft', 'building');
CREATE INDEX IF NOT EXISTS route_saved_search_idx ON route (saved_search_id, created_at DESC);
CREATE INDEX IF NOT EXISTS route_search_run_idx ON route (search_run_id);

COMMENT ON COLUMN route.geometry IS 'GeoJSON LineString; при наличии PostGIS заменить на geography(LineString,4326).';

-- Промежуточные точки маршрута (старт/финал дублируются в route для быстрых выборок).
CREATE TABLE IF NOT EXISTS route_waypoint (
    route_id   bigint NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    seq        smallint NOT NULL CHECK (seq > 0),
    city_id    bigint REFERENCES city (id) ON DELETE SET NULL,
    place_id   bigint REFERENCES place (id) ON DELETE SET NULL,
    latitude   double precision NOT NULL,
    longitude  double precision NOT NULL,
    PRIMARY KEY (route_id, seq),
    CONSTRAINT route_waypoint_lat_ck CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT route_waypoint_lon_ck CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX IF NOT EXISTS route_waypoint_city_idx ON route_waypoint (city_id, route_id);

-- Сегменты: пешком -> метро -> автобус -> пешком и т.п.
CREATE TABLE IF NOT EXISTS route_segment (
    route_id          bigint NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    seq               smallint NOT NULL CHECK (seq > 0),
    transport_mode_id smallint NOT NULL
                      REFERENCES transport_mode (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    from_lat          double precision NOT NULL,
    from_lon          double precision NOT NULL,
    to_lat            double precision NOT NULL,
    to_lon            double precision NOT NULL,
    distance_m        integer NOT NULL DEFAULT 0 CHECK (distance_m >= 0),
    duration_s        integer NOT NULL DEFAULT 0 CHECK (duration_s >= 0),
    instruction       text,
    street            text,
    geometry          jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (route_id, seq),
    CONSTRAINT route_segment_from_lat_ck CHECK (from_lat BETWEEN -90 AND 90),
    CONSTRAINT route_segment_from_lon_ck CHECK (from_lon BETWEEN -180 AND 180),
    CONSTRAINT route_segment_to_lat_ck CHECK (to_lat BETWEEN -90 AND 90),
    CONSTRAINT route_segment_to_lon_ck CHECK (to_lon BETWEEN -180 AND 180)
);

CREATE INDEX IF NOT EXISTS route_segment_mode_idx ON route_segment (transport_mode_id);

-- ---------------------------------------------------------------------------
-- Погода по городам: «сейчас» и по дням (WeatherAPI current.json / forecast.json)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS weather_current (
    city_id       bigint PRIMARY KEY REFERENCES city (id) ON DELETE CASCADE,
    observed_at   timestamptz NOT NULL,         -- current.last_updated
    local_time_label text,                      -- location.localtime (строка в tz города)
    temperature_c numeric(5, 2) NOT NULL,       -- current.temp_c
    feelslike_c   numeric(5, 2),                -- current.feelslike_c
    condition_code smallint,                    -- current.condition.code
    condition_text text,                        -- current.condition.text
    icon_url      text,                         -- current.condition.icon
    wind_kph      numeric(6, 2),                -- current.wind_kph
    wind_dir      text,                         -- current.wind_dir
    humidity      smallint CHECK (humidity BETWEEN 0 AND 100),
    precip_mm     numeric(6, 2),                -- current.precip_mm
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weather_daily (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    city_id          bigint NOT NULL REFERENCES city (id) ON DELETE CASCADE,
    forecast_date    date NOT NULL,
    source           text NOT NULL DEFAULT 'weatherapi',
    temp_min_c       numeric(5, 2),
    temp_max_c       numeric(5, 2),
    temp_avg_c       numeric(5, 2),
    feelslike_min_c  numeric(5, 2),
    feelslike_max_c  numeric(5, 2),
    max_wind_kph     numeric(6, 2),
    wind_dir         text,
    humidity         smallint CHECK (humidity BETWEEN 0 AND 100),
    precip_mm        numeric(6, 2),
    chance_of_rain   smallint CHECK (chance_of_rain BETWEEN 0 AND 100),
    chance_of_snow   smallint CHECK (chance_of_snow BETWEEN 0 AND 100),
    condition_code   smallint,
    condition_text   text,
    icon_url         text,
    uv               smallint CHECK (uv >= 0),
    sunrise_local    time,                      -- локальное время города
    sunset_local     time,
    fetched_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT weather_daily_uq UNIQUE (city_id, forecast_date, source)
);

CREATE INDEX IF NOT EXISTS weather_daily_city_date_idx ON weather_daily (city_id, forecast_date DESC);

-- ---------------------------------------------------------------------------
-- Кэш внешних API (уменьшает число вызовов 2ГИС/WeatherAPI)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS external_api_cache (
    cache_key  char(64) PRIMARY KEY,            -- sha256(provider|endpoint|params)
    provider   text NOT NULL CHECK (provider IN ('2gis', 'weatherapi')),
    payload    jsonb NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    hit_count  bigint NOT NULL DEFAULT 0 CHECK (hit_count >= 0)
);

CREATE INDEX IF NOT EXISTS external_api_cache_expiry_idx ON external_api_cache (expires_at);

-- ---------------------------------------------------------------------------
-- Технические триггеры updated_at
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER app_user_updated_at BEFORE UPDATE ON app_user
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER city_updated_at BEFORE UPDATE ON city
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER place_updated_at BEFORE UPDATE ON place
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER saved_search_updated_at BEFORE UPDATE ON saved_search
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER route_updated_at BEFORE UPDATE ON route
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER weather_current_updated_at BEFORE UPDATE ON weather_current
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

